// lvl('l01', { name, intro, outro, hs: { id: { n: name, look, look2, lock, do, done } } }) -> flat keys
function lvl(k, o) {
  S[k + '.name'] = o.name; S[k + '.intro'] = o.intro; S[k + '.outro'] = o.outro;
  for (const id in o.hs) {
    const h = o.hs[id];
    if (h.n) S[k + '.' + id] = h.n;
    for (const f of ['look', 'look2', 'lock', 'do', 'done']) if (h[f]) S[k + '.' + id + '.' + f] = h[f];
  }
}
