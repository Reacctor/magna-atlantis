// Lists the art files that exist into js/art-files.js, so the engine requests only those (no 404s in the console).
// Run after new art lands in art/: node tools/build-art-index.js
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const files = [];
for (const dir of ['scenes', 'characters', 'items', 'ui']) {
  const d = path.join(root, 'art', dir);
  if (!fs.existsSync(d)) continue;
  for (const f of fs.readdirSync(d).sort()) if (/\.(jpe?g|png|webp)$/i.test(f)) files.push(dir + '/' + f);
}
const out = '// Generated by tools/build-art-index.js: art files present in art/. Do not edit by hand.\n' +
  'window.ART_FILES = ' + JSON.stringify(files, null, 1).replace(/\n\s*/g, ' ') + ';\n';
fs.writeFileSync(path.join(root, 'js/art-files.js'), out);
console.log('art files: ' + files.length);
